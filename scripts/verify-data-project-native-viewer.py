#!/usr/bin/env python3
"""Verify a real native viewer against an owner native client.

The owner and viewer processes are already authenticated and expose the
loopback ``/api/invoke`` bridge.  The native sync acceptance report supplies
the owner project, cloud project, and the isolated viewer account created for
that fixture.  This script deliberately never reads or prints credentials;
the viewer process is expected to have been started with the private
credentials file generated by ``verify-data-project-native-sync.py``.
"""

import argparse
import datetime
import importlib.util
import json
import sys
import urllib.error
import urllib.request
from pathlib import Path


_spec = importlib.util.spec_from_file_location(
    "native_versioning",
    Path(__file__).with_name("verify-data-project-versioning.py"),
)
if _spec is None or _spec.loader is None:
    raise RuntimeError("cannot load the native acceptance helper")
_module = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(_module)
Acceptance = _module.Acceptance


def report_value(report, *names):
    """Read a report field from either its current or legacy location."""
    for name in names:
        if name in report and report[name]:
            return report[name]
        nested = report.get("ids")
        if isinstance(nested, dict) and nested.get(name):
            return nested[name]
    raise ValueError("native sync report is missing a required fixture identifier")


class ViewerAcceptance:
    def __init__(self, owner_url, viewer_url, sync_report):
        self.owner = Acceptance(owner_url)
        self.viewer = Acceptance(viewer_url)
        self.sync_report = sync_report
        self.owner_project = report_value(
            sync_report, "clientAProjectId", "ownerProjectId", "projectId"
        )
        self.owner_dataset = report_value(
            sync_report, "clientADatasetId", "ownerDatasetId", "datasetId"
        )
        self.remote_project = report_value(sync_report, "remoteProjectId")
        self.viewer_user = report_value(sync_report, "viewerId", "viewerUserId")
        self.checks = []

    def check(self, name, condition):
        if not condition:
            raise AssertionError(name)
        self.checks.append({"name": name, "passed": True})
        print(name, flush=True)

    @staticmethod
    def images(api, dataset_id):
        return api.call(
            "list_project_images",
            {"projectId": dataset_id, "groupId": None, "offset": 0, "limit": 200},
        )

    @staticmethod
    def dataset_name(api, dataset_id):
        for dataset in api.call("list_dataset_projects"):
            if dataset.get("id") == dataset_id:
                return dataset.get("name", "")
        return ""

    @staticmethod
    def try_call(api, command, args):
        """Return (accepted, value) without retaining an error body/token."""
        try:
            return True, api.call(command, args)
        except (RuntimeError, AssertionError, urllib.error.URLError):
            return False, None

    def find_viewer_dataset(self, owner_images, viewer_project):
        owner_name = self.dataset_name(self.owner, self.owner_dataset)
        candidates = []
        for dataset_id in viewer_project.get("datasetIds", []):
            images = self.images(self.viewer, dataset_id)
            by_name = {image.get("fileName"): image for image in images}
            overlap = sum(
                1 for image in owner_images if image.get("fileName") in by_name
            )
            same_name = owner_name and self.dataset_name(self.viewer, dataset_id) == owner_name
            candidates.append((bool(same_name), overlap, dataset_id, images))
        if not candidates:
            raise AssertionError("viewer clone has no materialized dataset")
        candidates.sort(key=lambda item: (item[0], item[1]), reverse=True)
        same_name, overlap, dataset_id, images = candidates[0]
        self.check("viewer clone materializes the owner's image dataset", overlap >= 3)
        return dataset_id, images

    def run(self):
        owner_remote_projects = self.owner.call("list_remote_data_projects")
        owner_remote = next(
            (item for item in owner_remote_projects if item.get("id") == self.remote_project),
            None,
        )
        self.check(
            "owner still discovers the synchronized cloud project",
            owner_remote is not None and owner_remote.get("role") in {"owner", "admin", "editor"},
        )

        viewer_remote_projects = self.viewer.call("list_remote_data_projects")
        viewer_remote = next(
            (item for item in viewer_remote_projects if item.get("id") == self.remote_project),
            None,
        )
        self.check(
            "viewer discovers the cloud project with viewer ACL",
            viewer_remote is not None and viewer_remote.get("role") == "viewer",
        )

        cloned = self.viewer.call(
            "clone_remote_data_project", {"remoteProjectId": self.remote_project}
        )
        viewer_project_id = cloned["localProjectId"]
        viewer_project = next(
            (
                item
                for item in self.viewer.call("list_data_projects")
                if item.get("id") == viewer_project_id
            ),
            None,
        )
        if viewer_project is None:
            raise AssertionError("viewer clone did not create a local data project")
        owner_project = next(
            (
                item
                for item in self.owner.call("list_data_projects")
                if item.get("id") == self.owner_project
            ),
            None,
        )
        if owner_project is None:
            raise AssertionError("owner project from sync report is no longer present")
        self.check(
            "viewer clone contains every owner project dataset",
            set(viewer_project.get("datasetIds", []))
            and len(viewer_project.get("datasetIds", []))
            == len(owner_project.get("datasetIds", [])),
        )

        owner_images = self.images(self.owner, self.owner_dataset)
        if len(owner_images) < 3:
            raise AssertionError("owner fixture must contain at least three images")
        viewer_dataset, viewer_images = self.find_viewer_dataset(owner_images, viewer_project)
        by_name = {image.get("fileName"): image for image in viewer_images}
        owner_first = owner_images[0]
        viewer_first = by_name.get(owner_first.get("fileName"))
        if viewer_first is None:
            raise AssertionError("viewer clone is missing the first owner image")
        owner_main = next(
            (
                branch
                for branch in self.owner.call(
                    "list_data_project_branches", {"dataProjectId": self.owner_project}
                )
                if branch.get("name") == "main"
            ),
            None,
        )
        viewer_main = next(
            (
                branch
                for branch in self.viewer.call(
                    "list_data_project_branches", {"dataProjectId": viewer_project_id}
                )
                if branch.get("name") == "main"
            ),
            None,
        )
        self.check(
            "viewer clone imports the remote main ref",
            owner_main is not None
            and viewer_main is not None
            and viewer_main.get("headCommitId") == owner_main.get("headCommitId"),
        )
        self.check(
            "viewer clone restores actual image labels",
            self.owner.state(self.owner_dataset, owner_first["id"])["objects"]
            == self.viewer.state(viewer_dataset, viewer_first["id"])["objects"],
        )
        self.check(
            "viewer clone retains a merge commit with a second parent",
            any(
                commit.get("secondParentId")
                for commit in self.viewer.call(
                    "list_data_project_version_commits",
                    {"dataProjectId": viewer_project_id, "branch": "main"},
                )
            ),
        )
        self.check(
            "viewer clone starts with a clean worktree",
            not self.viewer.call(
                "get_data_project_working_tree", {"dataProjectId": viewer_project_id}
            )["changes"],
        )

        # Owner publishes a new real label.  The viewer must pull it through
        # the read-only path, not through a frontend-only status update.
        self.owner.call(
            "switch_data_project_branch",
            {"dataProjectId": self.owner_project, "branch": "main"},
        )
        owner_before = self.owner.state(self.owner_dataset, owner_first["id"])
        owner_x = owner_before["objects"][0]["bbox"]["x"]
        owner_updated_x = self.owner.edit(self.owner_dataset, owner_first["id"], 7)
        owner_commit = self.owner.call(
            "commit_data_project_branch",
            {
                "dataProjectId": self.owner_project,
                "branch": "main",
                "message": "只读成员验收：owner 发布新标签",
            },
        )
        owner_push = self.owner.call(
            "sync_data_project", {"dataProjectId": self.owner_project}
        )
        self.check(
            "owner commits and publishes a real annotation update",
            owner_updated_x != owner_x
            and owner_commit.get("id")
            and owner_push.get("outcome") == "pushed",
        )

        viewer_pull = self.viewer.call(
            "sync_data_project", {"dataProjectId": viewer_project_id}
        )
        viewer_first_after = self.viewer.state(viewer_dataset, viewer_first["id"])
        self.check(
            "viewer performs a read-only pull of the owner update",
            viewer_pull.get("outcome") == "pulled"
            and viewer_first_after["objects"][0]["bbox"]["x"] == owner_updated_x,
        )

        # A viewer may edit and commit an offline local draft, but it must not
        # turn that draft into a cloud push.  Accept either the explicit native
        # error or a future readOnlyAhead report, while checking the remote
        # owner's history never contains the viewer commit.
        viewer_x = self.viewer.edit(viewer_dataset, viewer_first["id"], 11)
        viewer_commit = self.viewer.call(
            "commit_data_project_branch",
            {
                "dataProjectId": viewer_project_id,
                "branch": "main",
                "message": "只读成员本地草稿，不应上传",
            },
        )
        sync_accepted, sync_value = self.try_call(
            self.viewer, "sync_data_project", {"dataProjectId": viewer_project_id}
        )
        read_only_ahead = (
            not sync_accepted
            or (isinstance(sync_value, dict) and sync_value.get("outcome") == "readOnlyAhead")
        )
        viewer_status = self.viewer.call(
            "get_data_project_sync_status", {"dataProjectId": viewer_project_id}
        )
        owner_status_before_revoke = self.owner.call(
            "get_data_project_sync_status", {"dataProjectId": self.owner_project}
        )
        owner_history_before_revoke = self.owner.call(
            "list_data_project_version_commits",
            {"dataProjectId": self.owner_project, "branch": "main"},
        )
        self.check(
            "viewer local commit is read-only and never uploaded",
            viewer_x != owner_updated_x
            and viewer_commit.get("id")
            and read_only_ahead
            and viewer_status.get("state") == "readOnlyAhead"
            and owner_status_before_revoke.get("remoteHead") == owner_commit.get("id")
            and not any(
                commit.get("id") == viewer_commit.get("id")
                for commit in owner_history_before_revoke
            ),
        )

        removed = self.owner.call(
            "remove_data_project_cloud_member",
            {"dataProjectId": self.owner_project, "userId": self.viewer_user},
        )
        self.check("owner revokes the native viewer member", removed.get("deleted") is True)

        discovery_accepted, discovery_value = self.try_call(
            self.viewer, "list_remote_data_projects", {}
        )
        viewer_still_discovers = discovery_accepted and any(
            item.get("id") == self.remote_project for item in (discovery_value or [])
        )
        sync_after_revoke_accepted, _ = self.try_call(
            self.viewer, "sync_data_project", {"dataProjectId": viewer_project_id}
        )
        owner_after_revoke = self.owner.call(
            "get_data_project_sync_status", {"dataProjectId": self.owner_project}
        )
        owner_label_after_revoke = self.owner.state(self.owner_dataset, owner_first["id"])
        self.check(
            "revoked viewer disappears from remote discovery",
            not viewer_still_discovers,
        )
        self.check(
            "revoked viewer cannot synchronize its connected project",
            not sync_after_revoke_accepted,
        )
        self.check(
            "owner data remains available after viewer revocation",
            owner_after_revoke.get("remoteHead") == owner_commit.get("id")
            and owner_label_after_revoke["objects"][0]["bbox"]["x"] == owner_updated_x,
        )
        return {
            "passed": True,
            "checkedAt": datetime.datetime.now(datetime.timezone.utc).isoformat(),
            "ownerNativeBackend": self.owner.base,
            "viewerNativeBackend": self.viewer.base,
            "remoteProjectId": self.remote_project,
            "ownerProjectId": self.owner_project,
            "viewerProjectId": viewer_project_id,
            "ownerDatasetId": self.owner_dataset,
            "viewerDatasetId": viewer_dataset,
            "ownerCommitId": owner_commit["id"],
            "viewerLocalCommitId": viewer_commit["id"],
            "viewerUserId": self.viewer_user,
            "checks": self.checks,
        }


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--owner-url", "--owner-native-url", dest="owner_url", required=True)
    parser.add_argument("--viewer-url", "--viewer-native-url", dest="viewer_url", required=True)
    parser.add_argument(
        "--native-sync-report", "--sync-report", dest="sync_report", required=True
    )
    parser.add_argument("--output", required=True)
    args = parser.parse_args()
    output = Path(args.output)
    output.parent.mkdir(parents=True, exist_ok=True)
    try:
        report = json.loads(Path(args.sync_report).read_text())
        result = ViewerAcceptance(args.owner_url, args.viewer_url, report).run()
    except Exception as exc:
        # Keep the artifact useful for orchestration without copying native
        # error bodies that could accidentally contain private credentials.
        result = {
            "passed": False,
            "checkedAt": datetime.datetime.now(datetime.timezone.utc).isoformat(),
            "ownerNativeBackend": args.owner_url.rstrip("/"),
            "viewerNativeBackend": args.viewer_url.rstrip("/"),
            "errorType": type(exc).__name__,
        }
        output.write_text(json.dumps(result, ensure_ascii=False, indent=2) + "\n")
        print("native viewer acceptance failed: " + type(exc).__name__, file=sys.stderr)
        raise SystemExit(1)
    output.write_text(json.dumps(result, ensure_ascii=False, indent=2) + "\n")


if __name__ == "__main__":
    main()
